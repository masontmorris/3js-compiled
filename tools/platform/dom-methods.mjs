// Writes packages/three-native/src/platform/dom-methods.js: the names of the methods Edge's DOM defines on the
// element, node, event target and document interfaces a game reaches. The DOM stand-in logs a call to any of them
// it lacks. Run with `node tools/platform/dom-methods.mjs`.
import { writeFile, mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium } from 'playwright-core';

const profile = await mkdtemp(join(tmpdir(), 'threejsc-edge-'));
const timeout = setTimeout(() => { console.error('dom-methods: Edge did not finish within 5 minutes'); process.exit(1); }, 300_000);
let context;
try {
  context = await chromium.launchPersistentContext(profile, { channel: 'msedge', headless: true, timeout: 60_000 });
  const page = context.pages()[0] ?? await context.newPage();
  page.setDefaultTimeout(60_000);
  const names = await page.evaluate(() => {
    const interfaces = [HTMLCanvasElement, HTMLImageElement, HTMLInputElement, HTMLTextAreaElement, HTMLDivElement, HTMLBodyElement, HTMLHtmlElement, SVGElement, Document];
    const found = new Set();
    for (const Interface of interfaces) {
      for (let proto = Interface.prototype; proto && proto !== Object.prototype; proto = Object.getPrototypeOf(proto)) {
        for (const name of Object.getOwnPropertyNames(proto)) {
          const descriptor = Object.getOwnPropertyDescriptor(proto, name);
          if (typeof descriptor.value === 'function' && name !== 'constructor') found.add(name);
        }
      }
    }
    const handlers = proto => {
      const out = new Set();
      for (let p = proto; p && p !== Object.prototype; p = Object.getPrototypeOf(p)) {
        for (const name of Object.getOwnPropertyNames(p)) if (name.startsWith('on')) out.add(name.slice(2));
      }
      return [...out].sort();
    };
    const windowHandlers = [...new Set([...handlers(Object.getPrototypeOf(window)), ...Object.getOwnPropertyNames(window).filter(name => name.startsWith('on')).map(name => name.slice(2))])].sort();
    return { version: navigator.userAgent, names: [...found].sort(), handlers: { element: handlers(HTMLElement.prototype), document: handlers(Document.prototype), window: windowHandlers } };
  });
  const wrap = (list, indent) => list.map(name => `'${name}'`).join(', ').replace(/(.{1,110})(, |$)/g, `$1,\n${indent}`).trimEnd().replace(/,$/, '');
  const handlerLists = Object.entries(names.handlers).map(([kind, list]) => `  ${kind}: [\n    ${wrap(list, '    ')}\n  ],`).join('\n');
  await writeFile('packages/three-native/src/platform/dom-methods.js', `// Generated by tools/platform/dom-methods.mjs from ${names.version}.\nexport const DOM_METHODS = new Set([\n  ${wrap(names.names, '  ')}\n]);\n\n// The event handler attributes Edge defines on elements, the document and the window.\nexport const EVENT_HANDLERS = {\n${handlerLists}\n};\n`);
  console.log(`${names.names.length} methods from ${names.version}`);
} finally {
  clearTimeout(timeout);
  await context?.close();
  await rm(profile, { recursive: true, force: true });
}

// Writes packages/three-native/test/fixtures/dom-edge.js: what headless Edge gives for each scenario in
// test/fixtures/dom-scenarios.js. The Node and host tests compare the platform's results with it. Run with
// `node tools/platform/dom-reference.mjs`.
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium } from 'playwright-core';

const scenarios = await readFile('packages/three-native/test/fixtures/dom-scenarios.js', 'utf8');
const profile = await mkdtemp(join(tmpdir(), 'threejsc-edge-'));
const timeout = setTimeout(() => { console.error('dom-reference: Edge did not finish within 5 minutes'); process.exit(1); }, 300_000);
let context;
try {
  context = await chromium.launchPersistentContext(profile, { channel: 'msedge', headless: true, timeout: 60_000, viewport: { width: 1280, height: 720 } });
  const page = context.pages()[0] ?? await context.newPage();
  page.setDefaultTimeout(60_000);
  await page.route('https://reference.test/**', route => route.fulfill({ status: 200, contentType: 'text/html', body: '<!doctype html><body></body>' }));
  await page.goto('https://reference.test/');
  await page.addScriptTag({ type: 'module', content: `${scenarios}\nwindow.__scenarios = { mutations, delivery, exceptions, observerOptions, intersections, namespaces };` });
  await page.waitForFunction(() => window.__scenarios);
  const results = await page.evaluate(async () => {
    const s = window.__scenarios;
    return {
      version: navigator.userAgent,
      mutations: s.mutations(window),
      delivery: await s.delivery(window),
      exceptions: s.exceptions(window),
      observerOptions: s.observerOptions(window),
      intersections: await s.intersections(window),
      namespaces: s.namespaces(window),
    };
  });
  const { version, ...edge } = results;
  await writeFile('packages/three-native/test/fixtures/dom-edge.js', `// Generated by tools/platform/dom-reference.mjs from ${version}.\nexport const EDGE = ${JSON.stringify(edge, null, 2)};\n`);
  console.log(`dom-reference: ${Object.keys(edge).length} scenarios from ${version}`);
} finally {
  clearTimeout(timeout);
  await context?.close();
  await rm(profile, { recursive: true, force: true });
}
